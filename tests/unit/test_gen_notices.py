"""Tests for scripts/gen_notices.py."""

import importlib
from importlib import metadata
from pathlib import Path

import pytest

from gen_notices import (
    DEV_TITLE,
    MAX_TEXT,
    RUNTIME_TITLE,
    Notice,
    NoticeError,
    licence_texts,
    load_notice,
    lock_versions,
    main,
    render,
)

HASH = "a" * 64

RUNTIME_LOCK = f"""\
demolib==1.0 \\
    --hash=sha256:{HASH}
"""

DEV_LOCK = f"""\
demolib==1.0 \\
    --hash=sha256:{HASH}
demotool==2.5 \\
    --hash=sha256:{HASH}
"""


def make_dist(
    root: Path,
    name: str,
    version: str,
    extra: str = "",
    files: dict[str, str] | None = None,
) -> None:
    """Create a minimal installed distribution under root (a fake site-packages folder)."""
    info = root / f"{name}-{version}.dist-info"
    info.mkdir()
    header = f"Metadata-Version: 2.1\nName: {name}\nVersion: {version}\nLicense-Expression: MIT\n"
    (info / "METADATA").write_text(header + extra + "\n", encoding="utf-8")
    record = [f"{info.name}/METADATA,,"]
    for relative, text in (files or {}).items():
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        record.append(f"{relative},,")
    (info / "RECORD").write_text("\n".join(record) + "\n", encoding="utf-8")
    importlib.invalidate_caches()


def notice(name: str, text: str = "") -> Notice:
    texts = (("LICENSE", text),) if text else ()
    return Notice(name, "1.0", "MIT", f"https://example.invalid/{name}", texts)


@pytest.fixture
def site(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    root = tmp_path / "site"
    root.mkdir()
    monkeypatch.syspath_prepend(str(root))
    return root


def test_lock_versions_reads_pins_and_extras() -> None:
    text = f"""\
# autogenerated
uvicorn[standard]==0.30.0 \\
    --hash=sha256:{HASH}
    # via driftsniff
colorama==0.4.6 ; sys_platform == "win32" \\
    --hash=sha256:{HASH}
"""
    assert lock_versions(text) == {"uvicorn": "0.30.0", "colorama": "0.4.6"}


def test_licence_texts_keeps_licence_files_and_skips_code(site: Path) -> None:
    files = {
        "demolib-1.0.dist-info/licenses/LICENSE": "Licence A\r\n",
        "demolib/NOTICE.txt": "Notice B",
        "demolib/licenses.py": "LICENCES = 1",
        "demolib/COPYING": "Licence A",
    }
    make_dist(site, "demolib", "1.0", files=files)
    assert licence_texts(metadata.distribution("demolib")) == (
        ("demolib-1.0.dist-info/licenses/LICENSE", "Licence A"),
        ("demolib/NOTICE.txt", "Notice B"),
    )


def test_licence_texts_clips_a_very_long_file(site: Path) -> None:
    make_dist(site, "demolib", "1.0", files={"demolib/LICENSE": "x" * (MAX_TEXT + 500)})
    ((_, text),) = licence_texts(metadata.distribution("demolib"))
    assert text.endswith("[truncated: see the package for the full text]")
    assert len(text) < MAX_TEXT + 100


def test_load_notice_reads_licence_homepage_and_texts(site: Path) -> None:
    extra = "Home-page: https://example.invalid/demolib"
    files = {"demolib-1.0.dist-info/LICENSE": "Demo licence"}
    make_dist(site, "demolib", "1.0", extra, files)
    assert load_notice("demolib", "1.0") == Notice(
        name="demolib",
        version="1.0",
        licence="MIT",
        homepage="https://example.invalid/demolib",
        texts=(("demolib-1.0.dist-info/LICENSE", "Demo licence"),),
    )


def test_homepage_falls_back_to_the_first_project_url(site: Path) -> None:
    extra = "Home-page: UNKNOWN\nProject-URL: Source, https://example.invalid/src"
    make_dist(site, "demolib", "1.0", extra)
    assert load_notice("demolib", "1.0").homepage == "https://example.invalid/src"


def test_load_notice_rejects_a_version_other_than_the_lock(site: Path) -> None:
    make_dist(site, "demolib", "1.0")
    with pytest.raises(NoticeError, match="lock says 2.0 but 1.0 is installed"):
        load_notice("demolib", "2.0")


def test_load_notice_rejects_a_package_that_is_not_installed() -> None:
    with pytest.raises(NoticeError, match="demo-absent: not installed"):
        load_notice("demo-absent", "1.0")


def test_load_notice_describes_an_installed_package() -> None:
    found = load_notice("pytest", metadata.version("pytest"))
    assert found.name == "pytest"
    assert found.licence


def test_render_has_both_sections_in_order() -> None:
    text = render([notice("alpha", "Alpha text")], [notice("beta")])
    runtime_part, dev_part = text.split(DEV_TITLE)
    assert text.startswith("driftsniff third-party notices")
    assert RUNTIME_TITLE in runtime_part
    assert "alpha 1.0" in runtime_part
    assert "Licence: MIT" in runtime_part
    assert "Home page: https://example.invalid/alpha" in runtime_part
    assert "--- LICENSE ---\nAlpha text" in runtime_part
    assert "beta 1.0" in dev_part
    assert "alpha" not in dev_part
    assert text.endswith("\n")
    assert not text.endswith("\n\n")


def test_render_states_an_empty_section() -> None:
    _, dev_part = render([notice("alpha")], []).split(DEV_TITLE)
    assert "None." in dev_part


def test_main_writes_notices_with_dev_only_packages_apart(site: Path, tmp_path: Path) -> None:
    make_dist(site, "demolib", "1.0", files={"demolib-1.0.dist-info/LICENSE": "Demo licence"})
    make_dist(site, "demotool", "2.5")
    runtime = tmp_path / "requirements.txt"
    runtime.write_text(RUNTIME_LOCK, encoding="utf-8")
    dev = tmp_path / "requirements-dev.txt"
    dev.write_text(DEV_LOCK, encoding="utf-8")
    output = tmp_path / "NOTICES"
    assert main([str(runtime), str(dev), "--output", str(output)]) == 0
    runtime_part, dev_part = output.read_text(encoding="utf-8").split(DEV_TITLE)
    assert "demolib 1.0" in runtime_part
    assert "Demo licence" in runtime_part
    assert "demotool" not in runtime_part
    assert "demotool 2.5" in dev_part
    assert "demolib" not in dev_part


def test_main_reports_the_package_counts(
    site: Path, tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    make_dist(site, "demolib", "1.0")
    runtime = tmp_path / "requirements.txt"
    runtime.write_text(RUNTIME_LOCK, encoding="utf-8")
    output = tmp_path / "NOTICES"
    assert main([str(runtime), str(tmp_path / "none.txt"), "--output", str(output)]) == 0
    assert "1 runtime and 0 development-only packages" in capsys.readouterr().out


def test_main_writes_nothing_when_a_locked_package_is_missing(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    runtime = tmp_path / "requirements.txt"
    runtime.write_text(f"demo-absent==1.0 \\\n    --hash=sha256:{HASH}\n", encoding="utf-8")
    output = tmp_path / "NOTICES"
    assert main([str(runtime), str(tmp_path / "none.txt"), "--output", str(output)]) == 1
    assert not output.exists()
    assert "demo-absent: not installed" in capsys.readouterr().err


def test_main_rejects_an_unreadable_or_empty_runtime_lock(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    none = str(tmp_path / "none.txt")
    output = str(tmp_path / "NOTICES")
    assert main([str(tmp_path / "missing.txt"), none, "--output", output]) == 1
    assert "cannot read lock file" in capsys.readouterr().err
    empty = tmp_path / "empty.txt"
    empty.write_text("# nothing here\n", encoding="utf-8")
    assert main([str(empty), none, "--output", output]) == 1
    assert "no packages found" in capsys.readouterr().err
